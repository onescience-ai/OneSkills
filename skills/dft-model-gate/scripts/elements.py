def formula_str(counts):
    """把 {元素: 个数} 变成规范的 Hill 式字符串（无空格，字母序，C/H 优先）。"""
    keys = [k for k in counts if counts[k] > 0]
    if "C" in keys:
        order = ["C"] + (["H"] if "H" in keys else []) + sorted(k for k in keys if k not in ("C", "H"))
    elif "H" in keys:
        order = ["H"] + sorted(k for k in keys if k != "H")
    else:
        order = sorted(keys)
    return "".join("%s%s" % (k, counts[k] if counts[k] > 1 else "") for k in order)


def hill_formula_str(counts):
    """常见分子表使用的键格式：元素按字母序，个数为 1 时省略（H2O / CO2 / C2H6OS）。"""
    return "".join("%s%s" % (k, v if v > 1 else "") for k, v in sorted(counts.items()) if v > 0)
